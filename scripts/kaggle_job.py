"""Build a Kaggle kernel that runs one registered experiment at an exact commit.

The kernel clones this (public) repository, checks out the commit that triggered the workflow,
installs the package with the job's extras, runs the job's script and copies the declared result
files to ``/kaggle/working/results`` (Kaggle's output folder). Nothing else is written to the
output, so the repository itself never ends up in Kaggle outputs.

Usage (from the workflow):
    python scripts/kaggle_job.py build  --job m2_bm25 --sha <commit> --user <kaggle user> --out kjob
    python scripts/kaggle_job.py info --job m2_bm25 --user <kaggle user>  # slug, gpu, outputs
"""

from __future__ import annotations

import argparse
import json
import sys
from dataclasses import dataclass
from pathlib import Path

REPO_URL = "https://github.com/itsmarcusduong/vi-rag-agent.git"


@dataclass(frozen=True)
class Job:
    script: str
    extras: str
    outputs: tuple[str, ...]
    gpu: bool = False


JOBS: dict[str, Job] = {
    # Reproduction check: must match the GitHub Actions run of M2 exactly.
    "m2_bm25": Job("scripts/run_bm25.py", "retrieval,data", ("results/m2_bm25.json",)),
}

KERNEL_TEMPLATE = '''"""Auto-generated by scripts/kaggle_job.py. Do not edit on Kaggle."""
import os
import shutil
import subprocess
import sys

REPO_URL = {repo!r}
SHA = {sha!r}
EXTRAS = {extras!r}
SCRIPT = {script!r}
OUTPUTS = {outputs!r}


def sh(*args):
    print("+", " ".join(args), flush=True)
    subprocess.run(args, check=True)


os.environ["VI_RAG_RUNNER"] = "kaggle"
sh("git", "clone", "--quiet", REPO_URL, "/tmp/repo")
os.chdir("/tmp/repo")
sh("git", "checkout", "--quiet", SHA)
sh(sys.executable, "-m", "pip", "install", "--quiet", "-e", ".[" + EXTRAS + "]")
sh(sys.executable, SCRIPT)
os.makedirs("/kaggle/working/results", exist_ok=True)
for path in OUTPUTS:
    shutil.copy(path, "/kaggle/working/results/")
    print("saved", path, flush=True)
'''


def slug(job: str) -> str:
    """Kaggle derives the slug from the title: lowercase, dashes."""
    return "vi-rag-agent-" + job.lower().replace("_", "-")


def get_job(name: str) -> Job:
    if name not in JOBS:
        raise KeyError(f"unknown job {name!r}; registered: {sorted(JOBS)}")
    return JOBS[name]


def build(job_name: str, sha: str, user: str, out: Path) -> Path:
    job = get_job(job_name)
    if len(sha) != 40 or any(c not in "0123456789abcdef" for c in sha):
        raise ValueError("sha must be a full 40-character lowercase commit hash")
    out.mkdir(parents=True, exist_ok=True)
    code = KERNEL_TEMPLATE.format(
        repo=REPO_URL, sha=sha, extras=job.extras, script=job.script, outputs=job.outputs
    )
    (out / "run.py").write_text(code, encoding="utf-8")
    metadata = {
        "id": f"{user}/{slug(job_name)}",
        "title": slug(job_name),
        "code_file": "run.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": "true",
        "enable_gpu": "true" if job.gpu else "false",
        "enable_internet": "true",
        "dataset_sources": [],
        "competition_sources": [],
        "kernel_sources": [],
        "model_sources": [],
    }
    (out / "kernel-metadata.json").write_text(
        json.dumps(metadata, indent=2) + "\n", encoding="utf-8"
    )
    return out


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("command", choices=["build", "info"])
    parser.add_argument("--job", required=True)
    parser.add_argument("--user", required=True)
    parser.add_argument("--sha")
    parser.add_argument("--out", type=Path, default=Path("kjob"))
    args = parser.parse_args(argv)
    job = get_job(args.job)
    if args.command == "build":
        if not args.sha:
            parser.error("--sha is required for build")
        build(args.job, args.sha, args.user, args.out)
        print(args.out)
    else:
        print(f"kernel={args.user}/{slug(args.job)}")
        print(f"gpu={'true' if job.gpu else 'false'}")
        print(f"outputs={' '.join(job.outputs)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
